def _generated_at() -> str:
    source_date_epoch = os.getenv("SOURCE_DATE_EPOCH")
    if source_date_epoch:
        value = datetime.fromtimestamp(int(source_date_epoch), tz=timezone.utc)
    else:
        value = datetime.now(timezone.utc)
    return value.replace(microsecond=0).isoformat().replace("+00:00", "Z")


def build_site(root: Path, output: Path, repository_url: str = "") -> list[Agent]:
    root = root.resolve()
    output = output.resolve()
    agents = discover_agents(root, repository_url)
    output.mkdir(parents=True, exist_ok=True)
    assets = output / "assets"
    assets.mkdir(parents=True, exist_ok=True)

    generated_at = _generated_at()
    (output / "index.html").write_text(
        render_index(agents, generated_at), encoding="utf-8"
    )
    (output / "agents.json").write_text(
        json.dumps(
            {"generatedAt": generated_at, "agents": [asdict(agent) for agent in agents]},
            indent=2,
            ensure_ascii=False,
        )
        + "\n",
        encoding="utf-8",
    )
    (assets / "styles.css").write_text(STYLES, encoding="utf-8")
    (output / ".nojekyll").write_text("", encoding="utf-8")
    return agents


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=REPOSITORY_ROOT)
    parser.add_argument("--output", type=Path, default=REPOSITORY_ROOT / "docs")
    parser.add_argument(
        "--repository-url",
        default=os.getenv("AGENT_SAMPLES_REPOSITORY_URL", ""),
        help="Base URL to the repository tree used for agent-folder links.",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    try:
        agents = build_site(args.root, args.output, args.repository_url)
    except (OSError, ValueError) as exc:
        print(f"error: {exc}", file=__import__("sys").stderr)
        return 1
    print(f"Generated {args.output} with {len(agents)} agent(s).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

