def _generated_at() -> str:
    epoch = os.getenv("SOURCE_DATE_EPOCH")
    value = datetime.fromtimestamp(int(epoch), tz=timezone.utc) if epoch else datetime.now(timezone.utc)
    return value.replace(microsecond=0).isoformat().replace("+00:00", "Z")


def build_site(root: Path, output: Path, repository_url: str = "", release_base_url: str = "") -> list[Agent]:
    root, output = root.resolve(), output.resolve()
    agents = discover_agents(root, repository_url, release_base_url)
    output.mkdir(parents=True, exist_ok=True)
    generated_agents = output / "agents"
    if generated_agents.is_dir():
        shutil.rmtree(generated_agents)
    for child in output.iterdir():
        if child.is_dir() and (child / "index.html").is_file() and MARKER in (child / "index.html").read_text(encoding="utf-8", errors="ignore"):
            shutil.rmtree(child)
    (output / "assets").mkdir(exist_ok=True)
    generated = _generated_at()
    (output / "index.html").write_text(render_index(agents, generated), encoding="utf-8")
    for agent in agents:
        page = generated_agents / agent.application_slug / agent.use_case_slug
        page.mkdir(parents=True, exist_ok=True)
        (page / "index.html").write_text(render_agent(agent, generated), encoding="utf-8")
    (output / "agents.json").write_text(json.dumps({"schemaVersion":"1.0","generatedAt":generated,"agents":[asdict(a) for a in agents]}, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (output / "assets" / "styles.css").write_text(STYLES, encoding="utf-8")
    (output / ".nojekyll").write_text("", encoding="utf-8")
    return agents


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--output", type=Path, default=ROOT / "docs")
    parser.add_argument("--repository-url", default=os.getenv("AGENT_SAMPLES_REPOSITORY_URL", ""))
    parser.add_argument("--release-base-url", default=os.getenv("AGENT_SAMPLES_RELEASE_URL", ""))
    args = parser.parse_args()
    try:
        agents = build_site(args.root, args.output, args.repository_url, args.release_base_url)
    except (OSError, ValueError) as exc:
        print(f"error: {exc}", file=__import__("sys").stderr)
        return 1
    print(f"Generated {args.output} with {len(agents)} agent(s).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
